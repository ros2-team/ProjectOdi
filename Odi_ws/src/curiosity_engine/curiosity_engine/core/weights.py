# [curiosity_engine/core/weights.py]
#
# 호기심 엔진의 모든 튜닝 파라미터를 이 파일 하나에 모은다.
# calculator / policy / node 어디에도 숫자를 직접 박지 않는다.


# ============================================================
# 1. World Memory 조회
# ============================================================
# World Memory는 object_name이 일치하는 기록만 돌려준다.
# 즉 "선풍기를 봤으면 과거의 선풍기들만" 후보가 된다.
# max_results로 잘리므로 너무 작으면 visit_count가 과소평가된다.

MAX_SIMILAR_RESULTS = 30

# World Memory 응답 대기 시간(초)
WORLD_MEMORY_TIMEOUT = 5.0


# ============================================================
# 2. Similarity 가중치 (합 = 1.0)
# ============================================================
# object_name은 여기 없다.
# World Memory가 이미 같은 이름끼리만 걸러 주므로
# 후보 전원이 이름이 같아서 비교할 의미가 없기 때문이다.
#
# 따라서 "같은 선풍기인가?"는 색/재질/형태/상태로만 판단한다.

SIM_WEIGHTS = {
    'primary_color':   0.25,
    'material':        0.20,
    'shape':           0.20,
    'secondary_color': 0.15,
    'condition':       0.10,
    'special_features': 0.10,
}

# 이 값 이상이면 "같은 개체를 다시 만났다"고 판정
IDENTITY_THRESHOLD = 0.80


# ============================================================
# 3. Change 가중치 (합 = 1.0)
# ============================================================
# 변할 수 있는 속성만 대상으로 한다.
# condition(상태)이 가장 사건성이 크므로 배점이 가장 높다.
#   예) 세워져 있던 것이 쓰러짐, 깨끗하던 것이 더러워짐

CHANGE_WEIGHTS = {
    'condition':       0.55,
    'primary_color':   0.30,
    'secondary_color': 0.15,
}


# ============================================================
# 4. 점수 항 배점
# ============================================================

W_NOVELTY = 0.95
W_CHANGE = 0.95


# ============================================================
# 5. 기본 배점 (base)
# ============================================================
# "신규로 판정됐다" / "무언가 변했다" 는 사실 자체에 주는 최소 점수.

NOVELTY_BASE = 0.40
CHANGE_BASE = 0.50


# ============================================================
# 6. 익숙함 감쇠
# ============================================================
#   decay = 1 / (1 + VISIT_DECAY * visit_count)
#
# 주의: 이 감쇠는 novelty에만 곱한다. change에는 곱하지 않는다.
#       100번 본 물건이라도 오늘 상태가 변했으면 궁금해야 하기 때문.

VISIT_DECAY = 0.60


# ============================================================
# 7. 행동 결정 임계값
# ============================================================
# 프로젝트 문서 스펙상 Odi의 행동은 두 가지뿐이다.
#   OBSERVE : 가까이 접근해 정밀 관찰
#   IGNORE  : 추가 관찰 없이 탐험 계속
# 메인(Behavior Executor)이 이 두 문자열로 분기하므로
# 그 외의 값을 내보내면 아무 행동도 실행되지 않는다.

TH_OBSERVE = 0.50


# ============================================================
# 8. 탐사 제외 클래스
# ============================================================
# 구조물/배경은 정밀 관찰 대상이 아니다.
# person은 프라이버시 때문에 제외한다.

IGNORE_CLASSES = {
    'wall', 'floor', 'ceiling', 'door', 'window',
    'barrier', 'fence', 'stairs', 'pillar',
    'person',
}