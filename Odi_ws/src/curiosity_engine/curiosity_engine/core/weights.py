# [curiosity_engine/core/weights.py]
#
# 호기심 엔진의 모든 튜닝 파라미터를 이 파일 하나에 모은다.
# calculator / policy / node 어디에도 숫자를 직접 박지 않는다.


# ============================================================
# 1. 속성 분류
# ============================================================
# 정체성 속성 : 잘 변하지 않음 → "같은 개체인가?" 판정에 사용
# 상태 속성   : 변할 수 있음   → "무엇이 변했나?" 판정에 사용

IDENTITY_ATTRS = ('object_name', 'material', 'shape')
STATE_ATTRS = ('primary_color', 'secondary_color', 'condition')


# ============================================================
# 2. Similarity 가중치 (합 = 1.0)
# ============================================================
# 현재 관측 객체와 DB 기록의 "닮은 정도"를 계산할 때 쓰는 배점.
# 객체 종류가 가장 결정적이므로 배점이 가장 높다.

SIM_WEIGHTS = {
    'object_name':     0.30,
    'primary_color':   0.20,
    'material':        0.15,
    'shape':           0.15,
    'secondary_color': 0.10,
    'condition':       0.10,
}

# 이 값 이상이면 "같은 개체를 다시 만났다"고 판정
IDENTITY_THRESHOLD = 0.80


# ============================================================
# 3. Change 가중치 (합 = 1.0)
# ============================================================
# 변할 수 있는 속성만 대상으로 한다.
# condition(상태)이 가장 사건성이 크므로 배점이 가장 높다.
#   예) 세워져 있던 것이 쓰러짐, 깨끗하던 것이 더러워짐

CHANGE_WEIGHTS = {
    'condition':       0.55,
    'primary_color':   0.30,
    'secondary_color': 0.15,
}


# ============================================================
# 4. 점수 항 배점
# ============================================================
# 각 항이 단독으로 낼 수 있는 최대 점수.
# 1.0이 아니라 0.95인 이유: 어떤 관측도 "완벽히 확실"하지는 않으므로
# 아주 약간의 여유를 남겨둔다.

W_NOVELTY = 0.95
W_CHANGE = 0.95


# ============================================================
# 5. 기본 배점 (base)
# ============================================================
# "신규로 판정됐다" / "무언가 변했다" 는 사실 자체에 주는 최소 점수.
# 이게 없으면 항목 1개만 바뀐 사건이 지나치게 낮게 평가된다.

NOVELTY_BASE = 0.40
CHANGE_BASE = 0.50


# ============================================================
# 6. 익숙함 감쇠
# ============================================================
# 여러 번 본 객체일수록 novelty를 깎는다.
#   decay = 1 / (1 + VISIT_DECAY * visit_count)
#   0.6일 때 → 1회:0.63  2회:0.45  5회:0.25
# 값을 키우면 더 빨리 질려하고, 줄이면 오래 관심을 둔다.
#
# 주의: 이 감쇠는 novelty에만 곱한다. change에는 곱하지 않는다.
#       100번 본 물건이라도 오늘 상태가 변했으면 궁금해야 하기 때문.

VISIT_DECAY = 0.60


# ============================================================
# 7. 행동 결정 임계값
# ============================================================
# 위 설계에서 실제로 나오는 점수 분포에 맞춰 잡은 값.
#   완전 신규        ~0.95
#   기존 + 상태변화  ~0.76
#   애매한 신규      ~0.52
#   기존 + 변화없음   0.00
# 점수 설계를 바꾸면 이 값들도 반드시 같이 다시 잡아야 한다.

TH_APPROACH = 0.70   # 다가가서 정밀 조사
TH_OBSERVE = 0.50    # 원거리 관찰
TH_CAPTURE = 0.30    # 정지 후 촬영
TH_GLANCE = 0.15     # 흘끗 보고 지나감