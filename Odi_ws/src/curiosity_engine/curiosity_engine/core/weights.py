# [curiosity_engine/core/weights.py]
#
# 호기심 엔진의 모든 튜닝 파라미터를 이 파일 하나에 모은다.
# calculator / policy / node 어디에도 숫자를 직접 박지 않는다.


# ============================================================
# 1. 속성 분류
# ============================================================
# 정체성 속성 : 잘 변하지 않음 → "같은 개체인가?" 판정에 사용
# 상태 속성   : 변할 수 있음   → "무엇이 변했나?" 판정에 사용

IDENTITY_ATTRS = ('object_name', 'material', 'shape')
STATE_ATTRS = ('primary_color', 'secondary_color', 'condition')


# ============================================================
# 2. Similarity 가중치 (합 = 1.0)
# ============================================================
# 현재 관측 객체와 DB 기록의 "닮은 정도"를 계산할 때 쓰는 배점.
# 객체 종류가 가장 결정적이므로 배점이 가장 높다.

SIM_WEIGHTS = {
    'object_name':     0.30,
    'primary_color':   0.20,
    'material':        0.15,
    'shape':           0.15,
    'secondary_color': 0.10,
    'condition':       0.10,
}

# 이 값 이상이면 "같은 개체를 다시 만났다"고 판정
IDENTITY_THRESHOLD = 0.80


# ============================================================
# 3. Change 가중치 (합 = 1.0)
# ============================================================
# 변할 수 있는 속성만 대상으로 한다.
# condition(상태)이 가장 사건성이 크므로 배점이 가장 높다.
#   예) 세워져 있던 것이 쓰러짐, 깨끗하던 것이 더러워짐

CHANGE_WEIGHTS = {
    'condition':       0.55,
    'primary_color':   0.30,
    'secondary_color': 0.15,
}


# ============================================================
# 4. 점수 항 배점
# ============================================================
# 각 항이 단독으로 낼 수 있는 최대 점수.
# 1.0이 아니라 0.95인 이유: 어떤 관측도 "완벽히 확실"하지는 않으므로
# 아주 약간의 여유를 남겨둔다.

W_NOVELTY = 0.95
W_CHANGE = 0.95


# ============================================================
# 5. 기본 배점 (base)
# ============================================================
# "신규로 판정됐다" / "무언가 변했다" 는 사실 자체에 주는 최소 점수.
# 이게 없으면 항목 1개만 바뀐 사건이 지나치게 낮게 평가된다.

NOVELTY_BASE = 0.40
CHANGE_BASE = 0.50


# ============================================================
# 6. 익숙함 감쇠
# ============================================================
# 여러 번 본 객체일수록 novelty를 깎는다.
#   decay = 1 / (1 + VISIT_DECAY * visit_count)
#   0.6일 때 → 1회:0.63  2회:0.45  5회:0.25
# 값을 키우면 더 빨리 질려하고, 줄이면 오래 관심을 둔다.
#
# 주의: 이 감쇠는 novelty에만 곱한다. change에는 곱하지 않는다.
#       100번 본 물건이라도 오늘 상태가 변했으면 궁금해야 하기 때문.

VISIT_DECAY = 0.60


# ============================================================
# 7. 행동 결정 임계값
# ============================================================
# 프로젝트 문서 스펙상 Odi의 행동은 두 가지다.
#   OBSERVE : 가까이 접근해 정밀 관찰
#   IGNORE  : 추가 관찰 없이 탐험 계속
# 메인(Behavior Executor)이 이 두 문자열로 분기하므로
# 그 외의 값을 내보내면 아무 행동도 실행되지 않는다.
#
# 0.50인 이유 — 실제 점수 분포:
#   완전 신규        0.95   OBSERVE
#   애매한 신규      0.52   OBSERVE
#   기존 + 상태변화  0.75   OBSERVE
#   기존 + 색 변화   0.64   OBSERVE
#   기존 + 변화없음  0.00   IGNORE
# 값을 올리면 까다로워지고(관찰 수 감소),
# 내리면 호기심이 많아진다(관찰 수 증가).

TH_OBSERVE = 0.50

# ============================================================
# 8. 탐사 제외 클래스
# ============================================================
# 구조물/배경은 정밀조사 대상이 아니다.
# 지금은 DB가 비어 있어 모든 것이 신규 → 전부 APPROACH로 나오는데,
# 관찰 노드가 붙으면 로봇이 벽 앞에 가서 사진을 찍게 된다.
# person은 프라이버시 때문에 제외한다.
# (클로즈업을 찍어 외부 AI로 전송하는 경로를 만들지 않는다)

IGNORE_CLASSES = {
    'wall', 'floor', 'ceiling', 'door', 'window',
    'barrier', 'fence', 'stairs', 'pillar',
    'person',
}

# 이름이 다를 때 유사도 상한
NAME_MISMATCH_CAP = 0.30