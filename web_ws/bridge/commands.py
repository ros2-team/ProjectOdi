"""
명령 큐 — 웹이 로봇에게 말을 거는 유일한 통로.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
state.py 의 반대 방향
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

    state.py     로봇 → 웹      ros_link 가 쓰고 app 이 읽는다
    commands.py  웹 → 로봇      app 이 쓰고 ros_link 가 읽는다

거울처럼 대칭이다. 그래서 의존 방향 규칙이 그대로 유지된다.

    app ──▶ commands ◀── ros_link
          (쓰기)        (읽기)

★ app.py 가 ros_link 를 직접 부르면 안 되는 이유
  그러면 app 이 rclpy 를 import 하게 되고, ROS 없는 컴퓨터에서
  웹 서버가 아예 안 뜬다. 1단계에 화면을 전부 만들 수 있었던
  구조가 거기서 무너진다.

  큐를 하나 사이에 두면 app 은 "START 를 넣었다"까지만 알고,
  그게 ROS 토픽이 되는지 아무것도 안 되는지는 모른다.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
왜 리스트가 아니라 queue.Queue 인가
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

queue.Queue 는 락이 이미 안에 들어 있다.
Flask 스레드가 넣고 ROS 스레드가 꺼내는데, 리스트를 쓰면
state.py 처럼 LOCK 을 직접 관리해야 한다. 여기선 그럴 필요가 없다.
"""

# ┌─ 연결 지도 ────────────────────────────────────────────────
# │ ★ 이 파일은 아무것도 import 하지 않는다 (표준 라이브러리 제외).
# │
# │ 넣는 파일 : bridge/app.py    의 start_session()
# │ 꺼내는 파일 : bridge/ros_link.py 의 on_tick()
# └────────────────────────────────────────────────────────────

import queue

# maxsize=32 : 로봇이 안 떠 있어서 아무도 안 꺼내가면
# 버튼을 누른 만큼 무한히 쌓인다. 상한을 둬서 메모리를 지킨다.
_Q = queue.Queue(maxsize=32)


def send(name, detail=""):
    """명령을 넣는다. app.py 가 부른다.

        commands.send("START")
        commands.send("STOP", "사용자 취소")

    ★ 큐가 가득 차면 조용히 버린다.
      명령이 안 나가는 것보다 웹 요청이 블록되는 게 더 나쁘다.
      (로봇이 안 떠 있는 상태에서 버튼을 눌렀다는 뜻이므로,
       어차피 그 명령은 갈 곳이 없다)
    """
    try:
        _Q.put_nowait((name, detail))
        return True
    except queue.Full:
        return False


def drain():
    """쌓인 명령을 전부 꺼내 돌려준다. ros_link 의 on_tick 이 부른다.

    ★ 하나씩이 아니라 전부 꺼내는 이유
      on_tick 은 1 초에 한 번이다. 그 사이 버튼이 두 번 눌렸으면
      두 개가 쌓여 있는데, 하나만 꺼내면 나머지는 1 초씩 밀린다.

    반환: [("START", ""), ...]  없으면 빈 리스트
    """
    out = []
    while True:
        try:
            out.append(_Q.get_nowait())
        except queue.Empty:
            return out